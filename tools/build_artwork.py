#!/usr/bin/env python3
"""Prepare selected PlaneSlate catalog art for a personal T-Display-S3 build.
Sources retain their rights; see THIRD_PARTY.md. Requires Pillow only for rebuild.
"""
import json,struct
from pathlib import Path
from PIL import Image
BASE=Path(__file__).resolve().parents[1]
ROOT=BASE/'.local/current-assets'
INDEX=next(ROOT.rglob('index.jsonl'),None)
if INDEX is None:raise SystemExit('No local catalog. See docs/ARTWORK.md; the source-only build works without bitmap art.')
rows=[json.loads(x) for x in INDEX.read_text().splitlines()]
AIRLINES=set('CCA CES CSN CHH CSC CSZ CXA CQH DKH CUA GCR CDC CHB CBJ CQN CDG CBG RUI OKA LKE CSH SNG JYH HXA SWR KAL ANA JAL CPA SIA DLH AFR BAW UAE QTR THA AAL UAL DAL CAL EVA KLM THY'.split())
W,H=248,64

def bg(y):
 t=y/169
 return tuple(round(a+(b-a)*t) for a,b in zip((2,29,39),(1,88,91)))

def encode(im):
 im=im.convert('RGBA');im.thumbnail((W,H),Image.Resampling.LANCZOS)
 screen=Image.new('RGB',(W,H))
 for y in range(H):
  for x in range(W):screen.putpixel((x,y),bg(48+y))
 screen.paste(im,((W-im.width)//2,(H-im.height)//2),im)
 pixels=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in screen.getdata()]
 out=[];i=0
 while i<len(pixels):
  run=1
  while i+run<len(pixels) and pixels[i+run]==pixels[i] and run<32767:run+=1
  if run>=3:out.extend([0x8000|run,pixels[i]]);i+=run
  else:
   start=i;i+=run
   while i<len(pixels) and i-start<32767:
    if i+2<len(pixels) and pixels[i]==pixels[i+1]==pixels[i+2]:break
    i+=1
   out.append(i-start);out.extend(pixels[start:i])
 return struct.pack('<'+'H'*len(out),*out),screen

selected=[r for r in rows if r.get('layout')=='compact' and r.get('asset_type')!='airline_logo' and r.get('airline') in AIRLINES|{'*'}]
# Project additions are kept separate from the downloaded upstream catalog.
override_file=BASE/'assets/livery_overrides.json'
if override_file.exists():
 for override in json.loads(override_file.read_text()):
  key=(override['airline'],override['type'])
  selected=[r for r in selected if (r['airline'],r['type'])!=key]
  selected.append({**override,'project_asset':True})
paths={};bindings=[];total=0;asm=['.section .rodata.flight_art,"a"','.balign 4'];decl=[]
for r in selected:
 path=r['path']
 if path not in paths:
  n=len(paths);name=f'livery_{n}';paths[path]=name
  image=Image.open((BASE if r.get('project_asset') else ROOT)/path)
  if r.get('tight_crop'):
   image=image.convert('RGBA')
   bounds=image.getchannel('A').getbbox()
   if bounds is None:raise ValueError('Empty custom artwork: '+path)
   image=image.crop(bounds)
  data,preview=encode(image);total+=len(data)
  (BASE/'assets'/f'{name}.rle').write_bytes(data)
  asm.extend(['.balign 4',f'.global {name}',f'{name}:',f'.incbin "assets/{name}.rle"'])
  decl.append(f'extern const uint16_t {name}[];')
  if r['airline']=='CHH' and r['type']=='B738':preview.save(BASE/'.local/hainan-prepared.png')
  if r.get('project_asset'):preview.save(BASE/'.local'/f"{r['airline']}-{r['type']}-prepared.png")
 bindings.append((r['airline'],r['type'],paths[path]))
# Type and airline labels, without importing article text or registration history.
models={r['icao']:r.get('planeslate_name') or r.get('model') or r['icao'] for r in map(json.loads,next(ROOT.rglob('aircraft.jsonl')).read_text().splitlines())}
airlines={r['icao']:(r.get('airline_name') or r['icao'],r.get('iata','')) for r in map(json.loads,next(ROOT.rglob('airlines.jsonl')).read_text().splitlines())}
q=lambda x:json.dumps(x,ensure_ascii=True)
h=['#pragma once','#include <Arduino.h>','// Generated by tools/build_artwork.py; artwork attribution in THIRD_PARTY.md.','extern "C" {',*decl,'}',f'constexpr int ART_W={W},ART_H={H};','struct LiveryArt {const char*airline;const char*type;const uint16_t*data;};','static const LiveryArt LIVERIES[]={']
h.extend(f' {{{q(a)},{q(t)},{n}}},' for a,t,n in bindings);h+=['};','struct TypeLabel {const char*code;const char*name;};','static const TypeLabel TYPE_LABELS[]={'];h.extend(f' {{{q(t)},{q(models.get(t,t))}}},' for t in sorted({x[1] for x in bindings}));h+=['};','struct AirlineLabel {const char*code;const char*name;const char*iata;};','static const AirlineLabel AIRLINE_LABELS[]={'];h.extend(f' {{{q(a)},{q(airlines.get(a,(a,""))[0])},{q(airlines.get(a,(a,""))[1])}}},' for a in sorted(AIRLINES));h+=['};']
(BASE/'src/artwork.S').write_text('\n'.join(asm)+'\n');(BASE/'include/artwork.h').write_text('\n'.join(h)+'\n')
print('Livery bindings:',len(bindings),'unique images:',len(paths),'flash bytes:',total)
assert total<5000000,'Reduce selected airlines to fit the app partition'
# Verify RLE round trips and exact dimensions for every generated image.
for p in (BASE/'assets').glob('*.rle'):
 a=struct.unpack('<'+'H'*(p.stat().st_size//2),p.read_bytes());i=count=0
 while i<len(a):
  token=a[i];i+=1;n=token&32767;count+=n;i+=1 if token&32768 else n
 assert i==len(a) and count==W*H,p
print('All embedded image streams validated')
